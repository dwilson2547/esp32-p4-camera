#!/usr/bin/env python3
"""Generate imx477_settings.h from the Raspberry Pi Linux imx477.c (GPL-2.0).

Usage: gen_settings.py <path/to/imx477.c> <out.h>
Takes mode_common_regs and mode_2028x1520_regs verbatim, then overrides the
digital crop / output size to 1920x1520 (the ESP32-P4 ISP tops out at 1920 px
wide). mode_4056x3040_regs (full resolution, unbinned) is taken verbatim: it
is only captured raw, with the ISP bypassed.
"""
import math, re, sys

src = open(sys.argv[1]).read()

def table(name):
    m = re.search(r'static const struct cci_reg_sequence %s\[\] = \{(.*?)\n\};' % name, src, re.S)
    body = m.group(1)
    sym = {'IMX477_REG_DPHY_CTRL': 0x0808, 'IMX477_DPHY_CTRL_REGISTER': 2,
           'IMX477_REG_IOP_SYSCK_DIV': 0x030b, 'IMX477_IOP_SYSCK_DIV': 2,
           'IMX477_REG_IOP_PREDIV': 0x030d, 'IMX477_IOP_PREDIV': 2}
    out = []
    for a, v in re.findall(r'\{\s*([A-Za-z0-9_()]+)\s*,\s*([A-Za-z0-9_]+)\s*\}', body):
        mm = re.fullmatch(r'CCI_REG8\((0x[0-9a-fA-F]+)\)', a)
        addr = int(mm.group(1), 16) if mm else sym[a]
        val = int(v, 16) if v.startswith('0x') else sym[v]
        out.append((addr, val))
    return out

common = table('mode_common_regs')
mode = table('mode_2028x1520_regs')
full = table('mode_4056x3040_regs')

# Output geometry: digital crop is in post-binning coordinates (see the Linux
# 1332x990 mode: 2028-wide binned frame, X offset 348, width 1332).
OUT_W, OUT_H = 1920, 1520
X_OFF = (2028 - OUT_W) // 2      # 54, even -> Bayer phase unchanged
over = {0x0408: X_OFF >> 8, 0x0409: X_OFF & 0xff, 0x040a: 0, 0x040b: 0,
        0x040c: OUT_W >> 8, 0x040d: OUT_W & 0xff, 0x040e: OUT_H >> 8, 0x040f: OUT_H & 0xff,
        0x034c: OUT_W >> 8, 0x034d: OUT_W & 0xff, 0x034e: OUT_H >> 8, 0x034f: OUT_H & 0xff}
seen = set()
mode2 = []
for a, v in mode:
    if a in over:
        v = over[a]; seen.add(a)
    mode2.append((a, v))
assert seen == set(over), 'crop registers missing from mode table'

# Analog gain: gain = 1024 / (1024 - code), code 0..978. ~1/12 stop steps.
codes, gains = [], []
k = 0
while True:
    g = 2 ** (k / 12)
    c = round(1024 - 1024 / g)
    if c > 978:
        break
    if not codes or c > codes[-1]:
        codes.append(c); gains.append(round(1024000 / (1024 - c)))
    k += 1
if codes[-1] != 978:
    codes.append(978); gains.append(round(1024000 / (1024 - 978)))

def fmt(regs):
    rows = ['    {0x%04x, 0x%02x},' % rv for rv in regs]
    return '\n'.join(rows)

def arr(vals, per=8, w=6):
    return '\n'.join('    ' + ', '.join('%*d' % (w, x) for x in vals[i:i+per]) + ','
                     for i in range(0, len(vals), per))

h = f'''/*
 * SPDX-License-Identifier: GPL-2.0-only
 *
 * GENERATED by tools/gen_settings.py from the Raspberry Pi Linux driver
 * drivers/media/i2c/imx477.c (rpi-6.12.y, GPL-2.0). Do not edit by hand.
 */
#pragma once

#include <stdint.h>

typedef struct {{
    uint16_t reg;   /*!< register address, or IMX477_REG_END / IMX477_REG_DELAY */
    uint8_t  val;   /*!< value, or delay in ms for IMX477_REG_DELAY */
}} imx477_reginfo_t;

#define IMX477_REG_END    0xffff
#define IMX477_REG_DELAY  0xfffe

/* Linux mode_common_regs ({len(common)} writes). */
static const imx477_reginfo_t imx477_common_regs[] = {{
{fmt(common)}
    {{IMX477_REG_END, 0x00}},
}};

/*
 * Linux mode_2028x1520_regs (2x2 binned, full field), with the digital crop and
 * output size changed to {OUT_W}x{OUT_H}: X offset {X_OFF} in binned pixels.
 */
static const imx477_reginfo_t imx477_mode_{OUT_W}x{OUT_H}_regs[] = {{
{fmt(mode2)}
    {{IMX477_REG_END, 0x00}},
}};

/* Linux mode_4056x3040_regs (full resolution, no binning), verbatim. */
static const imx477_reginfo_t imx477_mode_4056x3040_regs[] = {{
{fmt(full)}
    {{IMX477_REG_END, 0x00}},
}};

/* Analog gain menu: total gain in milli-units, and the code that gives it. */
static const uint32_t imx477_total_gain_val_map[] = {{
{arr(gains)}
}};

static const uint16_t imx477_ana_gain_code_map[] = {{
{arr(codes)}
}};
'''
open(sys.argv[2], 'w').write(h)
print(f'common={len(common)} mode={len(mode2)} full={len(full)} gains={len(gains)} max={gains[-1]}')
